function setup() {
  createCanvas(800, 400);
}

function draw() {
  background(220);

  //-----------------------------------------------------------------------------

  //numbers

  fill(0);

  text("1.", 20, 15);
  text("2.", 20, 105);
  text("3.", 80, 105);
  text("4.", 80, 205);
  text("5.", 540, 20);
  text("6.", 350, 105);
  text("7.", 625, 105);

  //-----------------------------------------------------------------------------

  //1.

  for (let i1 = 0; i1 < 10; i1++) {
    if (i1 == 7) {
      fill(0, 0, 255)
    }
    else {
        fill (255)
      };
    rect(20 + (i1 * 50), 20, 50, 50);

  };

  //-----------------------------------------------------------------------------

  //2.

  for (let i2 = 0; i2 < 5; i2++) {
    fill(250 - (i2 * 60));
    rect(20, 110 + (i2 * 50), 50, 50);
  }

  //-----------------------------------------------------------------------------

  //3.

  for (let i3 = 0; i3 < 4; i3++) {
    rect(80, 110, 25 + (i3 * 25), 40)
  }

}
