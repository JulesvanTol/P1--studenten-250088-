function setup() {
  createCanvas(800, 400);
}

function draw() {
  background(220);
  strokeWeight(1);

  //-----------------------------------------------------------------------------

  //numbers

  fill(0);

  text("1.", 20, 15);
  text("2.", 20, 105);
  text("3.", 80, 105);
  text("4.", 80, 205);
  text("5.", 540, 20);
  text("6.", 350, 105);
  text("7.", 625, 105);

  //-----------------------------------------------------------------------------

  //1.

  for (let i1 = 0; i1 < 10; i1++) {
    if (i1 == 6) {
      fill(0, 0, 255)
    }
    else {
        fill (255)
      };
    rect(20 + (i1 * 50), 20, 50, 50);

  };

  //-----------------------------------------------------------------------------

  //2.

  for (let i2 = 0; i2 < 5; i2++) {
    fill(250 - (i2 * 60));
    rect(20, 110 + (i2 * 50), 50, 50);
  }

  //-----------------------------------------------------------------------------

  //3.

  for (let i3 = 0; i3 < 4; i3++) {
    fill(0, 0 + (i3 * 75), 0);
    rect(80 + (25 * i3 * (i3 + 1) * 0.5), 110, 25 + (i3 * 25), 40);
  }

  //-----------------------------------------------------------------------------

  //4.
  
  for (let i4 = 0; i4 < 4; i4++) {
    fill(0, 0, 225 - (i4 * 75));
    rect(80 + (25 * i4 * (i4 + 1) * 0.5), 210, 25 + (i4 * 25), 50 + (i4 * 25));
  }

  //-----------------------------------------------------------------------------

  //5.

  for (let i5 = 0; i5 < 5; i5++) {
    fill(255);
    strokeWeight(0 + (3 * i5));
    circle(560 + (i5 * 50), 45, 30);
  }

  //-----------------------------------------------------------------------------

  //6.

  strokeWeight(1)

  let ringColor = 0;

  for (let i6 = 0; i6 < 10; i6++) {
      if (i6 % 2 === 0) {
      ringColor = 0;
      } 
      else {
      ringColor = 255;
    }
    fill(255, ringColor, ringColor);
    circle(475, 215, 250 - (i6 * 25));
  }

  //-----------------------------------------------------------------------------

  //7.

  let rectLength = 10;
  let rectColor = 0;

  for (let i7 = 0; i7 < 21; i7++) {
    if (i7 <= 10) {
      rectLength = 10;
    }
    else {
      rectLength = (-20 * (i7 - 11) - 10);
    }
    if (i7 % 2 === 0) {
      rectColor = 100;
      } 
      else {
      rectColor = 255;
      }
    fill(rectColor);
    rect(625, 115 + (i7 * 10), 10 + ( i7 * 10 + rectLength), 10);
  }

}
